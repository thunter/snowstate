-- Control objects. In shared tenancy they sit beside the data objects.

CREATE TABLE IF NOT EXISTS TOKENS (
  TOKEN_ID     VARCHAR(36)  NOT NULL PRIMARY KEY,
  PRINCIPAL    VARCHAR(256) NOT NULL,
  TOKEN_HMAC   VARCHAR(64)  NOT NULL,
  SCOPES       VARIANT      NOT NULL,
  DESCRIPTION  VARCHAR(1024),
  CREATED_AT   TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CREATED_BY   VARCHAR(256),
  EXPIRES_AT   TIMESTAMP_TZ,
  REVOKED_AT   TIMESTAMP_TZ,
  LAST_USED_AT TIMESTAMP_TZ
);

CREATE TABLE IF NOT EXISTS PROJECTS (
  PROJECT     VARCHAR(128) NOT NULL PRIMARY KEY,
  SCHEMA_NAME VARCHAR(255) NOT NULL,
  ROLE_NAME   VARCHAR(255),
  PLAN_ROLE   VARCHAR(255),
  PERMISSIONS VARCHAR(255),
  CREATED_AT  TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CREATED_BY  VARCHAR(256)
);

-- Rows with no state key (token admin, GC) land here in schema_per_project.
CREATE TABLE IF NOT EXISTS AUDIT_LOG (
  EVENT_ID     VARCHAR(36)  NOT NULL,
  EVENT_TIME   TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  REQUEST_ID   VARCHAR(64),
  PRINCIPAL    VARCHAR(256),
  REMOTE_ADDR  VARCHAR(64),
  ACTION       VARCHAR(32)  NOT NULL,
  STATE_KEY    VARCHAR(512),
  VERSION_ID   VARCHAR(36),
  LOCK_ID      VARCHAR(128),
  RESULT       VARCHAR(16)  NOT NULL,
  HTTP_STATUS  NUMBER(3,0),
  DETAIL       VARIANT
);
